class Exercise1b {

    public static void main(String[] args) {

        // Initialize x with value 5
        int x = 5;

        // Loop continues while x is greater than 1
        while (x > 1) {

            // Decrease x by 1 each loop
            x = x - 1;

            // Check if x is less than 3
            if (x < 3) {

                // Print message when x is small
                System.out.println("small x");
            }
        }
    }
}