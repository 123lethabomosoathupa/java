public class DooBee {

    public static void main(String[] args) {

        // Initialize x with a value of 1
        int x = 1;

        // Repeat while x is less than 3
        while (x < 3) {

            // Print "Doo" without moving to a new line
            System.out.print("Doo");

            // Print "Bee" without moving to a new line
            System.out.print("Bee");

            // Increase x by 1
            x = x + 1;
        }

        // Check if x is equal to 3
        if (x == 3) {

            // Print "Do" without moving to a new line
            System.out.print("Do");
        }
    }
}